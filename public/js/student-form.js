window.__studentFormInit = function () {
  'use strict';
  var form = document.querySelector('form[action^="/admin/students"]');
  if (!form || form.__wired) return;
  form.__wired = true;

  var REQUIRED = ['admission_date','academic_year_id','class_id','roll_no','name','father_name','gender','guardian_phone'];
  var PHONE = /^(?:\+?880|0)1[3-9]\d{8}$/;

  function fieldOf(el){ return el.closest ? el.closest('.field') : null; }

  function star(el){
    var wrap = fieldOf(el); if (!wrap) return;
    var lab = wrap.querySelector('label'); if (!lab || lab.querySelector('.req')) return;
    var s = document.createElement('span'); s.className = 'req'; s.textContent = ' *';
    lab.appendChild(s);
  }

  // 1. Form No is generated by the server on save
  var isNewForm = form.getAttribute('action') === '/admin/students';
  var admNo = form.querySelector('[name="admission_no"]');
  if (admNo && isNewForm) {
    admNo.readOnly = true;
    admNo.title = 'Generated automatically';
    admNo.style.background = '#f3f4f6';
    if (!admNo.value) { admNo.placeholder = 'Generated automatically on save'; }
  }

  // 2. Admission date defaults to today
  var admDate = form.querySelector('[name="admission_date"]');
  if (admDate && !admDate.value) { admDate.value = new Date().toISOString().slice(0,10); }

  // 3. Roll number is filled by the server when left blank
  var roll = form.querySelector('[name="roll_no"]');
  if (roll && !roll.value) { roll.placeholder = 'Next number assigned automatically'; }

  // 4. student_type replaces the old boarding checkbox
  var legacy = form.querySelector('[name="is_resident"]');
  if (legacy) { var lw = fieldOf(legacy); if (lw) lw.style.display = 'none'; }

  // 4b. the single-line address is replaced by Village/Post/Thana/District
  var legacyAddress = form.querySelector('[name="address"]');
  if (legacyAddress && form.querySelector('[name="addr_village"]')) {
    var aw = fieldOf(legacyAddress); if (aw) aw.style.display = 'none';
  }

  // 5. Required markers
  REQUIRED.concat(['admission_type','student_type','is_orphan']).forEach(function (n) {
    var el = form.querySelector('[name="' + n + '"]');
    if (el) star(el);
  });

  // 6. Photo preview, camera and gallery
  var photo = form.querySelector('input[type=file][name="photo"]');
  if (photo && !photo.__enhanced) {
    photo.__enhanced = true;
    var holder = document.createElement('div');
    holder.style.cssText = 'display:flex;flex-wrap:wrap;gap:10px;align-items:center;margin-top:8px';
    var img = document.createElement('img');
    img.alt = 'Photo preview';
    img.style.cssText = 'width:84px;height:84px;object-fit:cover;border-radius:10px;border:1px solid var(--a-line);display:none';
    var pick = document.createElement('button');
    pick.type = 'button'; pick.className = 'btn btn-light btn-sm'; pick.textContent = 'Select from gallery';
    var shoot = document.createElement('button');
    shoot.type = 'button'; shoot.className = 'btn btn-light btn-sm'; shoot.textContent = 'Take photo';
    holder.appendChild(img); holder.appendChild(pick); holder.appendChild(shoot);
    photo.parentNode.insertBefore(holder, photo.nextSibling);
    photo.style.display = 'none';

    function show(file){
      if (!file) return;
      var u = URL.createObjectURL(file);
      img.src = u; img.style.display = 'block';
    }
    photo.addEventListener('change', function(){ show(photo.files[0]); });
    pick.addEventListener('click', function(){ photo.click(); });

    shoot.addEventListener('click', function () {
      if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) {
        photo.setAttribute('capture','user'); photo.click(); return;
      }
      var box = document.createElement('div');
      box.style.cssText = 'position:fixed;inset:0;background:rgba(10,20,16,.75);display:flex;align-items:center;justify-content:center;z-index:9999';
      var panel = document.createElement('div');
      panel.style.cssText = 'background:#fff;padding:16px;border-radius:14px;display:flex;flex-direction:column;gap:12px;max-width:92vw';
      var video = document.createElement('video');
      video.autoplay = true; video.playsInline = true;
      video.style.cssText = 'width:320px;max-width:84vw;border-radius:10px;background:#000';
      var row = document.createElement('div');
      row.style.cssText = 'display:flex;gap:10px;justify-content:flex-end';
      var cap = document.createElement('button'); cap.type='button'; cap.className='btn btn-primary btn-sm'; cap.textContent='Capture';
      var cancel = document.createElement('button'); cancel.type='button'; cancel.className='btn btn-light btn-sm'; cancel.textContent='Cancel';
      row.appendChild(cancel); row.appendChild(cap);
      panel.appendChild(video); panel.appendChild(row); box.appendChild(panel); document.body.appendChild(box);
      var stream = null;
      function close(){ if (stream) stream.getTracks().forEach(function(t){ t.stop(); }); box.remove(); }
      cancel.addEventListener('click', close);
      navigator.mediaDevices.getUserMedia({ video: { facingMode: 'user' } })
        .then(function (s) { stream = s; video.srcObject = s; })
        .catch(function () { close(); photo.setAttribute('capture','user'); photo.click(); });
      cap.addEventListener('click', function () {
        if (!video.videoWidth) return;
        var c = document.createElement('canvas');
        c.width = video.videoWidth; c.height = video.videoHeight;
        c.getContext('2d').drawImage(video, 0, 0);
        c.toBlob(function (blob) {
          if (!blob) { close(); return; }
          var file = new File([blob], 'photo.jpg', { type: 'image/jpeg' });
          try {
            var dt = new DataTransfer(); dt.items.add(file); photo.files = dt.files;
          } catch (e) {}
          show(file); close(); validate();
        }, 'image/jpeg', 0.9);
      });
    });
  }

  // 7. Validation gate
  var submit = form.querySelector('button[type=submit], button:not([type])');
  var note = document.createElement('p');
  note.className = 'hint';
  note.style.marginTop = '8px';
  if (submit && submit.parentNode) submit.parentNode.appendChild(note);

  function labelFor(el){
    var w = fieldOf(el);
    var l = w && w.querySelector('label');
    return l ? l.textContent.replace('*','').trim() : el.name;
  }

  function missing(){
    var bad = [];
    REQUIRED.forEach(function (n) {
      var el = form.querySelector('[name="' + n + '"]');
      if (!el) return;
      var v = String(el.value || '').trim();
      if (!v) { bad.push(labelFor(el)); return; }
      if (n === 'guardian_phone' && !PHONE.test(v.replace(/[\s-]/g,''))) {
        bad.push(labelFor(el) + ' (must be a valid 11-digit mobile)');
      }
    });
    return bad;
  }

  // Roll number follows the chosen class and session
  var cls = form.querySelector('[name="class_id"]');
  var yr = form.querySelector('[name="academic_year_id"]');
  function refreshRoll(){
    if (!roll || !cls || !cls.value) return;
    if (roll.value && !roll.dataset.auto) return;
    var q = '/admin/students/next-roll?class_id=' + encodeURIComponent(cls.value) +
            '&academic_year_id=' + encodeURIComponent(yr ? yr.value : '');
    fetch(q, { credentials: 'same-origin', headers: { 'X-Requested-With': 'fetch' } })
      .then(function (r) { return r.json(); })
      .then(function (d) {
        if (d && d.roll) { roll.value = d.roll; roll.dataset.auto = '1'; validate(); }
      })
      .catch(function () {});
  }
  if (cls) cls.addEventListener('change', refreshRoll);
  if (yr) yr.addEventListener('change', refreshRoll);
  if (roll) roll.addEventListener('input', function () { delete roll.dataset.auto; });
  refreshRoll();

  function validate(){
    var bad = missing();
    if (submit) submit.disabled = bad.length > 0;
    note.textContent = bad.length ? 'Still needed: ' + bad.join(', ') : '';
  }

  form.addEventListener('input', validate);
  form.addEventListener('change', validate);
  validate();
};
window.__studentFormInit();